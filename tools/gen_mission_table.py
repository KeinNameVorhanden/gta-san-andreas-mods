"""Generate the mission table of the mission_pass mod from a mission list, verified against main.scm.

The mission list is a markdown file with one table row per mission (all 135, in script order) and 11 columns, in
this order: index, thread name, pass key, title, size, CRC32 of the first 64 bytes, pass entry, how the entry was
found, 8 bytes at the entry, 0318 offset, S-key check. For example:

  | 12 | INTRO2 | INTRO_2 | Ryder | 16760 | DA277E91 | 13692 | S-target | 18 03 09 49 4e 54 52 4f | 13692 | 0735 @2334 |

"-" marks an empty cell. The CRC32 and the 8 bytes are hex; the pass entry and the 0318 offset are byte offsets from
the start of the mission. The size and S-key columns are informational. Lines that are not such a row (headers,
prose, other tables) are ignored.

Every row is checked against the real data/script/main.scm before it is written: CRC32 of the first 64 bytes of the
mission, the 8 bytes at the pass entry and REGISTER_MISSION_PASSED (18 03 09 + key) at the 0318 offset. Any mismatch
aborts, so the shipped table always matches the script file both supported builds use (byte-identical main.scm).

Usage:
    python tools/gen_mission_table.py --missions <mission list.md> --scm <game>/data/script/main.scm [--check]
"""

from __future__ import annotations

import argparse
import struct
import sys
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "mods" / "mission_pass" / "src" / "mission_table.inc"
MISSION_SEGMENT = 0xCFA4
MISSION_COUNT = 135


def mission_ranges(scm: bytes) -> list[tuple[int, int]]:
    """(start, end) file offsets of every mission, from the missions segment of the header."""
    base = MISSION_SEGMENT + 7 + 1  # GOTO with int32 target, then the segment id byte
    count = struct.unpack_from("<H", scm, base + 8)[0]
    if count != MISSION_COUNT:
        raise SystemExit(f"main.scm has {count} missions, expected {MISSION_COUNT}")
    offsets = list(struct.unpack_from(f"<{count}i", scm, base + 16))
    ends = offsets[1:] + [len(scm)]
    return list(zip(offsets, ends))


def mission_rows(missions: Path) -> list[dict]:
    rows = []
    for line in missions.read_text(encoding="utf-8").splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) != 11 or not cells[0].isdigit():
            continue
        idx, thread, key, title, _size, crc, entry, how, entry_bytes, at318, _skey = cells
        rows.append({
            "index": int(idx),
            "thread": "" if thread == "-" else thread,
            "key": "" if key == "-" else key,
            "title": "" if title == "-" else title,
            "crc": int(crc, 16),
            "entry": -1 if entry == "-" else int(entry),
            "how": how,
            "bytes": bytes.fromhex(entry_bytes) if entry != "-" else b"",
            "at318": -1 if at318 == "-" else int(at318),
        })
    if len(rows) != MISSION_COUNT:
        raise SystemExit(f"mission list has {len(rows)} rows, expected {MISSION_COUNT}")
    return rows


# Missions without a title in the mission list that the player sees under a name.
TITLES = {2: "In the Beginning", 36: "Lowrider meeting"}

# Excluded from the IP redirect (several REGISTER_MISSION_PASSED sites or a race manager).
NO_REDIRECT = {35, 48, 133}


def verify(rows: list[dict], scm: bytes) -> None:
    for row, (start, end) in zip(rows, mission_ranges(scm)):
        block = scm[start:end]
        crc = zlib.crc32(block[:64]) & 0xFFFFFFFF
        if crc != row["crc"]:
            raise SystemExit(f"mission {row['index']}: crc {crc:08X} != table {row['crc']:08X}")
        if row["entry"] >= 0:
            if block[row["entry"]:row["entry"] + 8] != row["bytes"]:
                raise SystemExit(f"mission {row['index']}: bytes at pass entry differ")
            key = row["key"].encode("ascii")
            if block[row["at318"]:row["at318"] + 3 + len(key)] != b"\x18\x03\x09" + key:
                raise SystemExit(f"mission {row['index']}: REGISTER_MISSION_PASSED not at {row['at318']}")
        row["size"] = end - start


def render(rows: list[dict]) -> str:
    out = [
        "// Generated by tools/gen_mission_table.py, verified against main.scm",
        "// (SHA-256 601def3b...68b0fa, identical in both supported builds). Do not edit by hand.",
        "// index, CRC32 of the first 64 bytes, size, pass entry (-1 none), 8 bytes at the entry, 0318 offset,",
        "// pass key, title, redirect allowed",
    ]
    for r in rows:
        entry_bytes = ", ".join(f"0x{b:02X}" for b in r["bytes"]) if r["bytes"] else "0"
        title = TITLES.get(r["index"]) or r["title"].replace('"', '\\"') or r["thread"]
        redirect = "true" if r["entry"] >= 0 and r["index"] not in NO_REDIRECT else "false"
        out.append(
            f'{{{r["index"]}, 0x{r["crc"]:08X}u, {r["size"]}, {r["entry"]}, {{{entry_bytes}}}, {r["at318"]}, '
            f'"{r["key"]}", "{title}", {redirect}}},'
        )
    return "\n".join(out) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--missions", required=True, type=Path,
                        help="mission list: markdown table, one row per mission (format in this script's docstring)")
    parser.add_argument("--scm", required=True, type=Path, help="data/script/main.scm of a supported install")
    parser.add_argument("--check", action="store_true", help="only verify, do not write")
    args = parser.parse_args()
    scm = args.scm.read_bytes()
    rows = mission_rows(args.missions)
    verify(rows, scm)
    text = render(rows)
    if args.check:
        same = OUTPUT.exists() and OUTPUT.read_text(encoding="utf-8") == text
        print("table verified" + ("" if same else f", {OUTPUT.name} is out of date"))
        return 0 if same else 1
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT.relative_to(ROOT)}: {len(rows)} missions verified")
    return 0


if __name__ == "__main__":
    sys.exit(main())
