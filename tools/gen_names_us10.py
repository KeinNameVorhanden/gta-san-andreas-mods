"""Generate tools/data/names_us10.json: 1.0 US function addresses -> names, from plugin-sdk sources (Zlib license).

Sources inside plugin_sa/game_sa:
    addrof(Class::Function) = ADDRESS_BY_VERSION(0x......, ...)
    wrapper bodies that call a fixed address: plugin::Call<0x...>, CallMethod<0x...>, CallAndReturn<..., 0x...>,
    and RenderWare.cpp style casts ((type(__cdecl *)(...))0x......)(...); the name is the enclosing function.
Only addresses inside the 1.0 US code section (0x401000..0x857000) are kept.

Usage:
    python tools/gen_names_us10.py [--sdk downloads/plugin-sdk]
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
OUT = REPO / "tools" / "data" / "names_us10.json"
CODE_START, CODE_END = 0x401000, 0x857000

ADDROF = re.compile(r"\baddrof(?:_o)?\(([^)]+)\)\s*=\s*ADDRESS_BY_VERSION\(\s*0x([0-9A-Fa-f]+)")
DEFINITION = re.compile(r"^[A-Za-z_][\w:<>\*&\s,]*?\b((?:[A-Za-z_]\w*::)*~?[A-Za-z_]\w*)\s*\([^;]*\)\s*(?:const\s*)?\{\s*$")
CALL_ADDRESS = re.compile(r"(?:Call\w*(?:Dyn)?<[^;]*?|\)\s*)0x([0-9A-Fa-f]{6})\b")


def harvest(sdk: Path) -> dict[int, str]:
    names: dict[int, str] = {}
    for source in sorted((sdk / "plugin_sa" / "game_sa").rglob("*.cpp")):
        current = None
        for line in source.read_text(encoding="utf-8", errors="replace").splitlines():
            for match in ADDROF.finditer(line):
                names.setdefault(int(match.group(2), 16), match.group(1).strip())
            definition = DEFINITION.match(line)
            if definition:
                current = definition.group(1)
                continue
            if line.startswith("}"):
                current = None
                continue
            if current:
                for match in CALL_ADDRESS.finditer(line):
                    names.setdefault(int(match.group(1), 16), current)
    return {a: n for a, n in names.items() if CODE_START <= a < CODE_END}


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--sdk", type=Path, default=REPO / "downloads" / "plugin-sdk")
    args = parser.parse_args(argv)
    names = harvest(args.sdk)
    if not names:
        print(f"no names found under {args.sdk}")
        return 1
    OUT.write_text(json.dumps({"source": "plugin-sdk (Zlib), plugin_sa/game_sa, generated by tools/gen_names_us10.py",
                               "functions": {f"{a:#x}": n for a, n in sorted(names.items())}}, indent=0) + "\n",
                   encoding="utf-8")
    print(f"{len(names)} functions -> {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
